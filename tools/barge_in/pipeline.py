"""Runs the whole barge-in measurement in one command, and writes a report that always includes its limits.

Steps:
  1. make_clips.ps1   generate the speech clips and their manifest (Windows speech synthesiser)
  2. build_cases.py   build the case list (clip x minimum-speech setting)
  3. run.mjs          run every case in Chromium on the page's audio clock
  4. scoring          score the results and write results/barge-in/report.md

Usage (from the repo root, with the project venv active):
  python tools/barge_in/pipeline.py            # everything
  python tools/barge_in/pipeline.py --score    # only re-score an existing run

Outputs go to results/barge-in/ (git-ignored). The clips are regenerated, not stored, so the repo holds the method
and nothing that depends on a machine.
"""

from __future__ import annotations

import argparse
import datetime as dt
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = ROOT / "results" / "barge-in"
sys.path.insert(0, str(ROOT / "src"))

from voiceshop.evaluation.barge_in_scoring import load, render, score  # noqa: E402

LIMITS = """## What this measurement does and does not cover

- **Measured:** whether the stop decision cuts the agent's reply for real caller interruptions and for backchannels
  ("mm-hmm", "okay"), and how long after the caller's speech starts the reply is cut. All timing is on one browser
  audio clock.
- **Not measured:** the microphone and speaker hardware, the operating system's audio path, echo from the speaker
  into the microphone, and telephone networks. A real caller arrives through all of these, so real latency will be
  higher.
- **Speech:** synthetic, generated by the Windows speech synthesiser. Real callers vary more in pace, volume and
  accent.
- **Sample:** a small proof-of-concept set. Intervals are shown for every rate, and a small sample gives a wide
  interval. The verdict is a feasibility check, not a statistical claim about callers in general.
- **Decision rule:** a simple energy threshold with a minimum unbroken-speech time. It is not a trained model.
"""


def run(cmd: list[str], cwd: Path = ROOT) -> None:
    print("+", " ".join(cmd), flush=True)
    # The commands are fixed in this file (PowerShell, Python and Node with known script paths), not user input.
    subprocess.run(cmd, cwd=cwd, check=True)  # noqa: S603


def generate_and_run() -> None:
    if shutil.which("powershell") is None:
        raise SystemExit("powershell is needed to generate the clips (Windows speech synthesiser)")
    run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(HERE / "make_clips.ps1"),
         "-OutDir", str(OUT / "clips")])
    run([sys.executable, str(HERE / "build_cases.py")])
    if shutil.which("node") is None:
        raise SystemExit("node is needed to run the browser lab")
    run(["node", str(HERE / "run.mjs")], cwd=ROOT / "e2e")


def write_report() -> Path:
    results, cases = load(OUT / "results.json", OUT / "cases.json")
    rows = score(results, cases)
    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# Barge-in measurement report",
        "",
        f"Generated {stamp}. Cases: {len(results)}. Invalid cases: "
        f"{sum(1 for r in results if not r.get('valid') or r.get('error'))}.",
        "",
        "## Results by minimum-speech setting",
        "",
        render(rows),
        "",
        "Decision latency is measured from the caller's speech starting to the agent's audio being cut, on the "
        "browser audio clock. A setting can only be read against the three criteria in "
        "docs/barge-in-measurement.md section 5.",
        "",
        LIMITS,
    ]
    path = OUT / "report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--score", action="store_true", help="only re-score an existing run")
    args = parser.parse_args()
    if not args.score:
        generate_and_run()
    path = write_report()
    print(f"report written to {path}")


if __name__ == "__main__":
    main()
